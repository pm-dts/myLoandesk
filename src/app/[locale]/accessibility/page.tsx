import AccessibilityView, {
  getAccessibilityMetadata,
} from "@/views/AccessibilityView";
import { notFound } from "next/navigation";
import { setRequestLocale } from "next-intl/server";

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params;
  if (locale !== "es") notFound();
  return getAccessibilityMetadata("es");
}

export default async function LocalizedAccessibilityPage({
  params,
}: {
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params;
  if (locale !== "es") notFound();

  setRequestLocale("es");
  return <AccessibilityView locale="es" />;
}
